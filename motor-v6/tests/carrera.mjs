import assert from 'node:assert/strict';
import {crearRedCiclo} from '../src/fisica/red-ciclo.js';
import {iniciarCarrera,posicionCarrera,pasoCarrera,luzCruce} from '../src/fisica/carrera.js';
import {perfilArcade} from '../src/fisica/arcade.js';
const n=(id,x,z,cruce='ninguno')=>({id,posicion:[x,z],altura_m:0,cruce});
const tr=(id,desde,hasta,puntos)=>({id,desde,hasta,puntos,red:'ciclovia',ancho_m:4.5,pendiente:0,nivel:0});
const red=crearRedCiclo([{nodos:[n('a',0,0),n('b',0,10,'semaforo'),n('c',10,10),n('d',-10,10)],tramos:[tr('ab','a','b',[[0,0],[0,10]]),tr('bc','b','c',[[0,10],[10,10]]),tr('bd','b','d',[[0,10],[-10,10]])]}],{completo:true});
const perfil=perfilArcade('bike'),dt=1/60;
let c=iniciarCarrera(red,{x:1,z:2,y:0,rumbo:0});assert.ok(c);
assert.equal(posicionCarrera(red,c).x,1);
for(let i=0;i<48;i++)c=pasoCarrera(red,c,{},dt,perfil,0);
assert.equal(c.fase,'carrera');assert.equal(posicionCarrera(red,c).x,0);
assert.equal(iniciarCarrera(red,{x:5,z:2,y:0,rumbo:0}),null);
let rojo=0;while(luzCruce(red.nodos.get('b'),rojo)!=='rojo')rojo++;
for(let i=0;i<240;i++)c=pasoCarrera(red,c,{rama:'bc'},dt,perfil,rojo);
assert.equal(c.ruta.tramo,'ab');assert.ok(c.ruta.s<=10);assert.ok(c.velocidad<.01);
let verde=0;while(luzCruce(red.nodos.get('b'),verde)!=='verde')verde++;
for(let i=0;i<240&&c.ruta.tramo==='ab';i++)c=pasoCarrera(red,c,{rama:'bc'},dt,perfil,verde);
assert.equal(c.ruta.tramo,'bc');assert.equal(posicionCarrera(red,c).z,10);
assert.ok(Math.abs(c.distancia-8)<1e-8);assert.equal(c.cruces,1);
for(let i=0;i<120&&c.fase!=='fin';i++)c=pasoCarrera(red,c,{lateral:1},dt,perfil,verde);
assert.ok(Math.abs(c.carril)<=1.85);
console.log('OK: entrada continua, señal roja, rama explícita, carril limitado y salida métrica');
