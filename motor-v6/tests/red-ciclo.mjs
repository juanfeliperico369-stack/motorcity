import assert from 'node:assert/strict';
import { crearRedCiclo, muestraCiclo, proyectarCiclo, avanzarCiclo } from '../src/fisica/red-ciclo.js';
const nodo=(id,x,z,h=0,cruce='ninguno')=>({id,posicion:[x,z],altura_m:h,cruce});
const tramo=(id,desde,hasta,puntos,ancho_m=2,pendiente=0,nivel=0)=>({id,desde,hasta,puntos,ancho_m,pendiente,nivel,red:'ciclovia'});
const datos=[{nodos:[nodo('a',0,0),nodo('b',10,10,2,'semaforo'),nodo('c',20,10,2),nodo('d',10,20,2)],tramos:[tramo('ab','a','b',[[0,0],[10,0],[10,10]],2,.1),tramo('bc','b','c',[[10,10],[20,10]],3),tramo('bd','b','d',[[10,10],[10,20]],1.5)]}];
const red=crearRedCiclo(datos,{completo:true});
assert.equal(red.tramos.get('ab').largo,20);
assert.deepEqual(muestraCiclo(red,{tramo:'ab',s:5,sentido:1}),{x:5,z:0,y:.5,rumbo:Math.PI/2,ancho_m:2,carriles:2,pendiente:.1,nivel:0});
assert.equal(muestraCiclo(red,{tramo:'ab',s:15,sentido:-1}).pendiente,-.1);
assert.equal(muestraCiclo(red,{tramo:'ab',s:10,sentido:-1}).rumbo,-Math.PI/2);
const entrada=proyectarCiclo(red,{x:5,z:.5,rumbo:-Math.PI/2,nivel:0});
assert.equal(entrada.tramo,'ab');assert.equal(entrada.sentido,-1);assert.deepEqual(entrada.origen,{x:5,z:.5});assert.equal(entrada.distancia_m,.5);
assert.equal(proyectarCiclo(red,{x:5,z:3}),null);
assert.equal(proyectarCiclo(red,{x:5,z:0,nivel:1}),null);
const inicio={tramo:'ab',s:19,sentido:1};
const cruce=avanzarCiclo(red,inicio,3);
assert.equal(cruce.evento,'cruce');assert.equal(cruce.restante_m,2);assert.equal(cruce.posicion.x,10);assert.equal(cruce.posicion.z,10);
const bifurca=avanzarCiclo(red,cruce.estado,2,{pasoPermitido:true});
assert.equal(bifurca.evento,'bifurcacion');assert.deepEqual(bifurca.opciones.map(x=>x.tramo),['bc','bd']);
assert.throws(()=>avanzarCiclo(red,cruce.estado,2,{pasoPermitido:true,rama:'inexistente'}),/Rama/);
const transicion=avanzarCiclo(red,cruce.estado,2,{pasoPermitido:true,rama:'bc'});
assert.equal(transicion.evento,'transicion');assert.equal(transicion.restante_m,2);
assert.equal(transicion.posicion.x,cruce.posicion.x);assert.equal(transicion.posicion.z,cruce.posicion.z);assert.equal(transicion.posicion.y,cruce.posicion.y);
assert.equal(transicion.posicion.carriles,3);
const avance=avanzarCiclo(red,transicion.estado,transicion.restante_m);
assert.equal(avance.posicion.x,12);assert.equal(avance.posicion.z,10);
const final=avanzarCiclo(red,avance.estado,20);assert.equal(final.evento,'fin');assert.equal(final.posicion.x,20);
const parcial=crearRedCiclo(datos);assert.equal(avanzarCiclo(parcial,avance.estado,20).evento,'sin_datos');
assert.throws(()=>crearRedCiclo([{nodos:[datos[0].nodos[0]],tramos:datos[0].tramos}],{completo:true}),/ausentes/);
console.log('OK: polilínea, reversa, entrada, nivel, semáforo, bifurcación, ancho, continuidad de posición y datos pendientes');
