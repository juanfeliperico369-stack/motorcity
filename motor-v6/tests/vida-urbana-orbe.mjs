import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {VidaUrbana} from '../src/mundo/vida-urbana.js';
import {muestraVial} from '../src/fisica/trafico.js';
import {luzCruce} from '../src/fisica/carrera.js';
const dir=process.argv[2],idx=JSON.parse(fs.readFileSync(path.join(dir,'indice.json')));
const ss=idx.sectores.map(c=>JSON.parse(fs.readFileSync(path.join(dir,c.url))));
const inv=JSON.parse(fs.readFileSync(process.argv[3])),vida=new VidaUrbana({topologia:ss,inventario:inv});
const s=ss.find(s=>s.id===inv.sector);
vida.sincronizarPlaza(s);const malla=vida.adoquin.malla;vida.sincronizarPlaza(s);assert.equal(vida.adoquin.malla,malla);
const v=[...vida.red.carriles.values()].find(c=>c.hasta==='n_km0'&&c.largo>100),d=[...vida.red.carriles.values()].find(c=>c.desde==='n_km0'&&c.tramo!==v.tramo&&c.largo>100);
const p=muestraVial(v,v.largo-35),jugador={...p,radio:.4,alto:1.72};
assert.ok(vida.agregar({id:'correo',inicio:v.id,destino:d.id,s:v.largo-45,jugador}));
assert.equal(vida.agregar({id:'ocupado',inicio:v.id,destino:d.id,s:v.largo-35,jugador}),false);
let e;
for(let i=0;i<900;i++)e=vida.paso(1/60,i/60,jugador);
assert.equal(e.actores[0].estado,'obstaculo');assert.equal(e.cruces,0);
const a=e.actores[0],b=vida.bloquear({...jugador,x:a.x-5,z:a.z,y:a.y},{...jugador,x:a.x+5,z:a.z,y:a.y});
assert.equal(b.tipo,'trafico');
const f=inv.piezas[0];assert.equal(vida.bloquear({x:f.x-2,z:f.z,y:f.y,radio:.3,alto:1.72},{x:f.x,z:f.z,y:f.y,radio:.3,alto:1.72}).tipo,'mobiliario');
for(let i=900;i<6300;i++){e=vida.paso(1/60,i/60,{...jugador,x:0,z:0});if(e.cruces)break;}
assert.equal(e.cruces,1);
const dibujo=vida.dibujar({x:1350,z:1110,radio:300});
assert.equal(dibujo.muebles,27);assert.equal(dibujo.obstaculos,38);assert.equal(dibujo.senales.estados.length,11);assert.ok(dibujo.adoquin>0);
for(const e of dibujo.senales.estados)assert.equal(e.fase,luzCruce(vida.red.nodos.get(e.nodo),vida.reloj));
vida.sincronizarPlaza(null);assert.equal(vida.adoquin,null);assert.equal(vida.obstaculos.length,38);
vida.sincronizarPlaza(s);assert.notEqual(vida.adoquin.malla,malla);
vida.cerrar();assert.equal(vida.raiz.children.length,0);assert.throws(()=>vida.dibujar({x:0,z:0}),/cerrada/);
console.log('OK: VidaUrbana integrada, tráfico, ruta, jugador, reloj, 38 huellas y ciclo de vida de plaza');
