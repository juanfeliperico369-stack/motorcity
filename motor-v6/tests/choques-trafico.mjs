import assert from 'node:assert/strict';
import {crearCarrilesViales} from '../src/fisica/trafico.js';
import {RedTrafico} from '../src/fisica/red-trafico.js';
import {choqueRelativo,bloqueaJugador,pasoProtegidoJugador} from '../src/fisica/choques-trafico.js';
const p=(x,z,y=0)=>({x,z,y,radio:.4,alto:1.72});
assert.ok(choqueRelativo(p(-10,0),p(10,0),p(0,-10),p(0,10)));
assert.ok(!choqueRelativo(p(-10,0,10),p(10,0,10),p(0,-10),p(0,10)));
assert.ok(!choqueRelativo(p(-10,3),p(10,3),p(0,0),p(0,0)));
const nodos=[{id:'a',posicion:[0,0],altura_m:0},{id:'b',posicion:[0,160],altura_m:0}];
const v={id:'v',red:'vial',desde:'a',hasta:'b',nivel:0,ancho_m:10,puntos:[[0,0],[0,160]]},c={...v,id:'c',red:'ciclovia',ancho_m:4.5,circulacion:{tipo:'lateral',vial:'v',offset_m:2.75,transicion_m:25}};
const sim=new RedTrafico(crearCarrilesViales([{nodos,tramos:[v,c]}]));
sim.agregar({id:'coche',ruta:['v:1'],s:40});
const jugador=p(3.625,60);let e;
for(let i=0;i<900;i++)e=pasoProtegidoJugador(sim,1/60,jugador);
const a=e.actores[0];assert.equal(a.estado,'obstaculo');assert.equal(a.velocidad,0);assert.ok(a.z<60-2);
assert.equal(bloqueaJugador(e.actores,p(-3,a.z),p(8,a.z)),'coche');
assert.equal(bloqueaJugador(e.actores,p(-3,a.z,10),p(8,a.z,10)),null);
const antes=a.s;for(let i=0;i<120;i++)e=pasoProtegidoJugador(sim,1/60,p(-10,60));assert.ok(e.actores[0].s>antes+3);
console.log('OK: barrido relativo, alturas, bloqueo mutuo jugador/tráfico y reanudación; 1020 pasos');
